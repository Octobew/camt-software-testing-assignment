// Writes a Liquibase formatted-SQL changeset that inserts seed users.
// Users come from the same UserBuilder the tests use, so names are Thai (fakerTH)
// and every national id has a valid checksum.
//
//   npx tsx scripts/generate-user-seed.ts --role COMMISSIONER --count 5 \
//     --password commission1234 --out db/changelog/changes/902-seed-commissioners.sql
//
// Generate once, review, commit. Do not regenerate a file whose changeset has
// already run: the password salt is random, so the SQL and its checksum change.
import { writeFileSync } from 'node:fs';
import { parseArgs } from 'node:util';
import { faker, fakerTH } from '@faker-js/faker';
import { hashPassword } from '../src/auth/passwords';
import { Role } from '../src/domain/types';
import { DEFAULT_PASSWORD, UserBuilder, UserSpec } from '../test/support/builders';

const ROLES: readonly Role[] = ['VOTER', 'COMMISSIONER', 'ADMIN'];
// Seed accounts have a known password, so they may only go to throwaway environments.
const ALLOWED_CONTEXTS = ['dev', 'e2e'];

interface Options {
  role: Role;
  count: number;
  district: string;
  password: string;
  seed: number;
  context: string;
  changesetId: string;
  out?: string;
}

function readOptions(): Options {
  const { values } = parseArgs({
    options: {
      role: { type: 'string', default: 'COMMISSIONER' },
      count: { type: 'string', default: '3' },
      district: { type: 'string', default: 'CM-1' },
      password: { type: 'string', default: DEFAULT_PASSWORD },
      seed: { type: 'string', default: '20261003' },
      context: { type: 'string', default: 'dev' },
      id: { type: 'string' },
      out: { type: 'string' },
    },
  });

  const role = values.role.toUpperCase() as Role;
  if (!ROLES.includes(role)) throw new Error(`--role must be one of ${ROLES.join(', ')}`);

  const count = Number(values.count);
  if (!Number.isInteger(count) || count < 1) throw new Error('--count must be a positive integer');

  const seed = Number(values.seed);
  if (!Number.isInteger(seed)) throw new Error('--seed must be an integer');

  if (!ALLOWED_CONTEXTS.includes(values.context)) {
    throw new Error(`--context must be one of ${ALLOWED_CONTEXTS.join(', ')} (seed passwords are public)`);
  }

  return {
    role,
    count,
    district: values.district,
    password: values.password,
    seed,
    context: values.context,
    changesetId: values.id ?? `902-seed-${role.toLowerCase()}s`,
    out: values.out,
  };
}

/** `count` users with distinct national ids, all sharing one password hash. */
function buildUsers({ role, count, district, password }: Options): UserSpec[] {
  // scrypt is slow on purpose: hash once and reuse it. Fine for seed data, never for real users.
  const passwordHash = hashPassword(password);
  const byNationalId = new Map<string, UserSpec>();
  while (byNationalId.size < count) {
    const user = new UserBuilder(role).inDistrict(district).build();
    if (!byNationalId.has(user.nationalId)) byNationalId.set(user.nationalId, { ...user, passwordHash });
  }
  return [...byNationalId.values()];
}

const quote = (value: string) => `'${value.replaceAll("'", "''")}'`;

function toChangeset(options: Options, users: UserSpec[]): string {
  const { role, count, district, password, seed, context, changesetId } = options;
  const accounts = users.map((u) => `--   ${u.nationalId}  ${u.firstName} ${u.lastName}`);
  const values = users.map(
    (u) =>
      `    (${[u.nationalId, u.passwordHash, u.firstName, u.lastName, u.address, u.districtId, u.role]
        .map(quote)
        .join(', ')})`,
  );
  const ids = users.map((u) => quote(u.nationalId)).join(', ');

  return [
    '--liquibase formatted sql',
    '',
    '-- Generated by scripts/generate-user-seed.ts. Do not edit by hand.',
    `--   --role ${role} --count ${count} --district ${district} --seed ${seed} --context ${context}`,
    '--',
    `-- Accounts (national id, password ${password}):`,
    ...accounts,
    '',
    `--changeset election:${changesetId} context:${context}`,
    'INSERT INTO users (national_id, password_hash, first_name, last_name, address, district_id, role) VALUES',
    `${values.join(',\n')};`,
    `--rollback DELETE FROM users WHERE national_id IN (${ids});`,
    '',
  ].join('\n');
}

const options = readOptions();

// Same seed, same people: the output can be reproduced and reviewed.
faker.seed(options.seed);
fakerTH.seed(options.seed);

const users = buildUsers(options);
const sql = toChangeset(options, users);

if (options.out) {
  writeFileSync(options.out, sql);
  console.error(`wrote ${users.length} ${options.role} user(s) to ${options.out}`);
} else {
  process.stdout.write(sql);
}
